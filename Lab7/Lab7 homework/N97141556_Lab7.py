import numpy as np
from sklearn import sklearn
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

data = np.loadtxt("Bank_Customer.csv",skiprows=1,dtype=str,delimiter=',')

gender = np.where(data[:,3] == 'Male', 1, 0)

country = np.where(data[:,2] == 'Spain', 0, np.where(data[:,2] == 'France', 1, 2))

temp_data = data[:,[1,4,5,6,7,8,9,10]].astype(float)

y=data[:,11].astype(float)
features = np.column_stack((temp_data, gender, country))
features = StandardScaler().fit_transform(features)

pre_data = np.column_stack((features, y))
np.savetxt("Bank_Customer_Preprocessed.csv", pre_data, delimiter=",")

from sklearn.linear_model import LogisticRegression
# 決策分類器
clf = LogisticRegression()

x_train, x_test, y_train, y_test = train_test_split(features, y, test_size=0.3, random_state=0)

# 使用訓練集來訓練我們的分類器
clf.fit(x_train, y_train)
# 測試資料集中進行預測
pred = clf.predict(x_test)

#print (pred) # 預測分類，即客戶是否流失
#print (y_test) # 分類
print (str(accuracy_score(pred, y_test)*100 ) + "% ")   # 預測精度

